function createSets(count: number, defaultWeight: number, defaultReps: number): ExerciseSet[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `set-${Math.random().toString(36).slice(2, 9)}`,
    setNumber: i + 1,
    type: 'working',
    targetReps: `${defaultReps}`,
    actualWeightKg: defaultWeight,
    actualReps: defaultReps,
    completed: false,
  }));
}

